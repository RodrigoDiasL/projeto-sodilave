CREATE TABLE IF NOT EXISTS `ProductionStorageBalance` (
  `productionId` INT NOT NULL,
  `locationId` INT NOT NULL,
  `quantityPackages` INT NOT NULL,
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`productionId`,`locationId`),
  KEY `ProductionStorageBalance_locationId_idx` (`locationId`),
  CONSTRAINT `ProductionStorageBalance_productionId_fkey`
    FOREIGN KEY (`productionId`) REFERENCES `Production`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `ProductionStorageBalance_locationId_fkey`
    FOREIGN KEY (`locationId`) REFERENCES `StorageLocation`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `ProductionStorageBalance_quantity_chk` CHECK (`quantityPackages` >= 0)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `ProductionStorageMovement` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `productionId` INT NOT NULL,
  `movementType` VARCHAR(24) NOT NULL,
  `fromLocationId` INT NULL,
  `toLocationId` INT NULL,
  `quantityPackages` INT NOT NULL,
  `lotDispatchId` INT NULL,
  `createdById` INT NOT NULL,
  `reason` VARCHAR(500) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  KEY `ProductionStorageMovement_production_idx` (`productionId`,`createdAt`),
  KEY `ProductionStorageMovement_from_idx` (`fromLocationId`),
  KEY `ProductionStorageMovement_to_idx` (`toLocationId`),
  KEY `ProductionStorageMovement_dispatch_idx` (`lotDispatchId`),
  CONSTRAINT `ProductionStorageMovement_productionId_fkey`
    FOREIGN KEY (`productionId`) REFERENCES `Production`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `ProductionStorageMovement_fromLocationId_fkey`
    FOREIGN KEY (`fromLocationId`) REFERENCES `StorageLocation`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `ProductionStorageMovement_toLocationId_fkey`
    FOREIGN KEY (`toLocationId`) REFERENCES `StorageLocation`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `ProductionStorageMovement_lotDispatchId_fkey`
    FOREIGN KEY (`lotDispatchId`) REFERENCES `LotDispatch`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `ProductionStorageMovement_createdById_fkey`
    FOREIGN KEY (`createdById`) REFERENCES `User`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `ProductionStorageMovement_quantity_chk` CHECK (`quantityPackages` > 0)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
